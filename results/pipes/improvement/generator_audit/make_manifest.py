#!/usr/bin/env python3
"""Build the immutable source/input/output hash manifest for this audit."""

import hashlib
import json
import platform
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
OUT = Path(__file__).resolve().parent


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def rel(path):
    return str(path.relative_to(ROOT))


def record(path):
    return {"path": rel(path), "sha256": sha(path), "bytes": path.stat().st_size}


def main():
    summary_path = OUT / "geometry_runs" / "summary.json"
    summary = json.loads(summary_path.read_text())
    bridge = json.loads((OUT / "geometry_bridge.json").read_text())
    selected = [5, 8, 9, 10, 14, 15]
    outputs = {}
    resources = {}
    for row in summary["records"]:
        c = str(row["case"])
        case_dir = OUT / "geometry_runs" / "runs" / c
        outputs[c] = {name: record(case_dir / name) for name in
                      ("solver_stderr.txt", "judge_output.txt", "interactor_stderr.txt",
                       "score.txt")}
        resources[c] = {key: row[key] for key in
                        ("status", "solver_cpu_total_s", "solver_peak_rss_mb",
                         "wall_orchestration_s", "trench_length_m", "kpi")}

    inputs = {str(c): record(ROOT / "data/pipes/open" / f"{c}.in") for c in selected}
    synthetic_dir = ROOT / "results/pipes/improvement/flow_predictors/synthetic"
    synthetic = {p.name: record(p) for p in sorted(synthetic_dir.glob("*.in"))}
    previous = [
        ROOT / "results/pipes/improvement/flow_predictors/REPORT.md",
        ROOT / "results/pipes/improvement/lifetime/REPORT.md",
        ROOT / "results/pipes/improvement/survival_hazard/REPORT.md",
        ROOT / "results/pipes/improvement/generator_audit/audit.py",
        ROOT / "results/pipes/improvement/generator_audit/audit.json",
    ]
    outputs_audit = [
        OUT / "GENERATOR_AUDIT.md", OUT / "geometry_bridge.py",
        OUT / "geometry_bridge.json", OUT / "geometry_replay.cpp",
        OUT / "geometry_replay", OUT / "make_manifest.py",
        OUT / "geometry_runs/summary.json", OUT / "geometry_runs/cases.csv",
        ROOT / "tools/pipes_harness.py", ROOT / "tools/interactor",
    ]
    compiler = subprocess.run(["c++", "--version"], capture_output=True, text=True).stdout.splitlines()[0]
    manifest = {
        "audit": "prequential rank-to-neighbor-gap/coalescence bridge",
        "decision": "negative; no placement policy implemented; no KPI screen run",
        "created_utc_date": "2026-10-17",
        "canonical_source": record(ROOT / "results/pipes/final/solution.cpp"),
        "canonical_source_expected_sha256": "c4b737b9a14588dd9895450acaff804b140691ef4d41bf1a0d68b6f13232a991",
        "instrumented_source": record(OUT / "geometry_replay.cpp"),
        "instrumented_binary": record(OUT / "geometry_replay"),
        "compile_command": "c++ -std=c++17 -O2 -pipe -Wall -Wextra -Wpedantic -DGENERATOR_AUDIT_LOG geometry_replay.cpp -o geometry_replay",
        "compiler": compiler,
        "host_platform": summary["host_platform"],
        "python_version": summary["python_version"],
        "interactor": record(ROOT / "tools/interactor"),
        "harness": record(ROOT / "tools/pipes_harness.py"),
        "split": {"train_initial_operations_fraction": 0.40,
                  "validation_next_operations_fraction": 0.20,
                  "test_final_operations_fraction": 0.40,
                  "cases": selected},
        "rank_definition": bridge["rank_definition"],
        "uncertainty": "2,000 block-bootstrap replicates; non-overlapping 128-operation blocks; CI reported per case",
        "input_hashes": inputs,
        "existing_synthetic_rank_only_inputs_not_replayed_for_geometry": synthetic,
        "previous_audits": {str(p.relative_to(ROOT)): sha(p) for p in previous},
        "geometry_bridge_analysis": record(OUT / "geometry_bridge.py"),
        "geometry_bridge_results": record(OUT / "geometry_bridge.json"),
        "harness_summary": record(summary_path),
        "harness_cases_csv": record(OUT / "geometry_runs/cases.csv"),
        "case_resources": resources,
        "case_output_hashes": outputs,
        "audit_artifacts": [record(p) for p in outputs_audit],
        "limitations": [
            "observational geometry generated by the baseline allocator, not an intervention",
            "only six public open cases were geometry-instrumented",
            "existing synthetic inputs were not used to validate rank-to-coalescence transfer",
            "debug logging made case 15 exceed 5 CPU seconds; this is not submission-resource evidence",
        ],
    }
    out_path = OUT / "manifest.json"
    out_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    print(out_path)
    print(sha(out_path))
    print("canonical_source_sha256", sha(ROOT / "results/pipes/final/solution.cpp"))


if __name__ == "__main__":
    main()
